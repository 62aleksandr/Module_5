/**
 * @brief  The application entry point.
 * @retval int
 */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_ADC1_Init();
  MX_TIM1_Init();
  MX_TIM2_Init();
  MX_TIM3_Init();
  MX_USART2_UART_Init();
  /* USER CODE BEGIN 2 */
  HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_1);
  HAL_TIM_Base_Start_IT(&htim2);
  HAL_TIM_Base_Start_IT(&htim3);

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    if (pid_flag)
    {
      pid_flag = 0;

      HAL_ADC_Start(&hadc1);

      if (HAL_ADC_PollForConversion(&hadc1, 1) == HAL_OK)
      {
        adc = HAL_ADC_GetValue(&hadc1);
      }

      // Розрахунок помилки
      err = setpoint - adc;

      // Інтегральна сумма помилок
      errSUM += err;

      // Пропорційна складова
      P = Kp * err;

      // Інтегральна складова
      I = Ki * errSUM;

      // Диференційна складова
      D = Kd * ((err - err0) / dt);

      // PID
      pwm = P + I + D;

      // Обмеження PWM
      if (pwm < 0)
        pwm = 0;

      if (pwm > 4095)
        pwm = 4095;

      // PWM
      TIM1->CCR1 = pwm * 16;
      // Для контроля
      ccr = TIM1->CCR1;
      // предыдущая ошибка
      err0 = err;
    }

    if (print_flag)
    {
      print_flag = 0;
      snprintf(trans_str, sizeof(trans_str), "adc = %d, err = %d,  pwm = %d, ccr = %d, P = %d, I = %d\r\n", adc, err, pwm, ccr, P, I);
      HAL_UART_Transmit(&huart2, (uint8_t *)trans_str, strlen(trans_str), 1000);
    }

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

